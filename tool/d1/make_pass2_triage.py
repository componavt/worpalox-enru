# --- merge with the pilot decisions (300 lines, earlier editorial pass)
pilot_map = {}
for r in csv.DictReader(open(OUT / "pilot_lines.csv", encoding="utf-8")):
    use = r["use"]
    if use == "PLAY":
        decision = "puzzle_candidate"
    elif use == "CONTEXT":
        decision = "context_candidate"
    else:
        decision = "reject"
    if r["translation_ok"] == "mismatch":
        decision = "needs_source_check"
    pilot_map[int(r["line_id"])] = (
        decision,
        f"pilot: {r['role']}, translation {r['translation_ok']}, "
        f"{r['confidence']} confidence",
    )

missing = [n for n in pilot_map if n not in D]
extra = [n for n in D if n not in pilot_map]
print(f"pilot rows: {len(pilot_map)}; hand triage rows: {len(D)}; "
      f"only in pilot: {len(missing)} {missing[:8]}; only in hand: {len(extra)} {extra[:8]}")

final = {}
for n, (dec, why) in D.items():
    final[n] = (dec, why, "pass2_hand")
for n, (dec, why) in pilot_map.items():
    final[n] = (dec, why, "pass2_pilot")

rows_out = []
for n in sorted(final):
    dec, why, source = final[n]
    rows_out.append((n, source, dec, why))

with (OUT / "pass2_triage.csv").open("w", encoding="utf-8", newline="") as f:
    w = csv.writer(f)
    w.writerow(["line_id", "source", "decision", "reason"])
    w.writerows(rows_out)

